const own = (object, key) => Object.hasOwn(object, key) ? object[key] : undefined;
export function attributeNote(table, column, relations = []) {
  if (typeof column.comment === 'string' && column.comment.trim()) return column.comment.trim();
  const context = own(specific, table);
  const note = (context && own(context, column.name)) || own(common, column.name);
  if (note) return note;
  const relation = relations.find(item => item.column === column.name);
  if (relation) return `Ссылка на запись ${relation.target}, поле ${relation.target_column}. Отдельное пояснение назначения пока не задано.`;
  return 'Описание назначения атрибута пока не задано.';
}
